<#
    .SYNOPSIS
    Builds the winGod dock executable (winGod-dock.exe) from the repo scripts.

    .DESCRIPTION
    Generates a single-file bundle (Logging + taskbar library + dock) whose
    entrypoint is emitted by the bundler itself and compiles it with PS2EXE
    (installed from the PowerShell Gallery when missing).

    .PARAMETER OutputDirectory
    Where the exe lands. Defaults to <repo>\build.

    .PARAMETER SkipModuleInstall
    Assume PS2EXE is already available for the current user.

    .EXAMPLE
    .\Build-WinGodDockExe.ps1
#>
[CmdletBinding()]
param(
    [string]$OutputDirectory,
    [switch]$SkipModuleInstall
)

$ErrorActionPreference = 'Stop'
$repositoryRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
if (-not $OutputDirectory) {
    $OutputDirectory = Join-Path $repositoryRoot 'build'
}
New-Item -Path $OutputDirectory -ItemType Directory -Force | Out-Null

if (-not $SkipModuleInstall -and -not (Get-Module -ListAvailable -Name ps2exe)) {
    try {
        [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
        if (-not (Get-PackageProvider -Name NuGet -ListAvailable -ErrorAction SilentlyContinue)) {
            Install-PackageProvider -Name NuGet -MinimumVersion 2.8.5.201 -Scope CurrentUser -Force -Confirm:$false | Out-Null
        }
        Install-Module -Name ps2exe -Scope CurrentUser -Force -SkipPublisherCheck -AllowClobber -Confirm:$false
    }
    catch {
        Write-Error "Unable to install ps2exe: $($_.Exception.Message)"
        exit 1
    }
}

$logging = Get-Content (Join-Path $repositoryRoot 'Scripts\Performance\Logging.ps1') -Raw -Encoding UTF8
$taskbar = Get-Content (Join-Path $repositoryRoot 'Scripts\Dock\Set-TaskbarAutoHide.ps1') -Raw -Encoding UTF8
$dock = Get-Content (Join-Path $repositoryRoot 'Scripts\Dock\Invoke-WinGodDock.ps1') -Raw -Encoding UTF8

# strip out repo-only dot-sources (the bundle carries its own copies) and the
# dock script header (the bundler wraps it as the entrypoint function)
$dock = $dock -replace [regex]::Escape('. "$PSScriptRoot\..\Performance\Logging.ps1"'), 'return-if-bundled'
$taskbarDotSource = '. (Join-Path ' + '$PSScriptRoot' + " 'Set-TaskbarAutoHide.ps1')"
$dock = $dock.Replace($taskbarDotSource, 'if ($false) { . (Join-Path $PSScriptRoot ''Set-TaskbarAutoHide.ps1'') }')
$dock = $dock -replace 'return-if-bundled', 'if ($false) { . "$PSScriptRoot\..\Performance\Logging.ps1" }'
$dock = $dock -replace '\[CmdletBinding\(\)\]\r?\nparam\(\r?\n\s*\[string\]\$ConfigPath,\r?\n\s*\[switch\]\$Stop,\r?\n\s*\[switch\]\$NoRunKey,\r?\n\s*\[switch\]\$OpenPanel\r?\n\)', 'param([string]$ConfigPath, [switch]$Stop, [switch]$NoRunKey, [switch]$OpenPanel)'

$bundle = @"
param([string]`$ConfigPath, [switch]`$Stop, [switch]`$NoRunKey, [switch]`$OpenPanel)

# winGod dock bundle - generated by Build-WinGodDockExe.ps1 (do not edit)

$logging

$taskbar

function Invoke-WinGodDockBundleEntry {
$dock
}

Invoke-WinGodDockBundleEntry -ConfigPath:`$ConfigPath -Stop:`$Stop -NoRunKey:`$NoRunKey -OpenPanel:`$OpenPanel
"@

$bundleFile = Join-Path $OutputDirectory 'winGod-dock-bundle.ps1'
Set-Content -Path $bundleFile -Value $bundle -Encoding UTF8

$exeFile = Join-Path $OutputDirectory 'winGod-dock.exe'
$parameters = @{
    inputFile    = $bundleFile
    outputFile   = $exeFile
    noConsole    = $true
    x64          = $true
    requireAdmin = $false
    STA          = $true
    title        = 'winGod dock'
    description  = 'winGod dock: barra dockada estilo macOS/lumabar para Windows 10/11.'
    company      = 'winGod'
    product      = 'winGod dock'
    copyright    = 'winGod project'
}
if (Test-Path (Join-Path $repositoryRoot 'Assets\winGod.ico')) {
    $parameters.iconFile = Join-Path $repositoryRoot 'Assets\winGod.ico'
}

Write-Host "Compilando $exeFile ..."
& Invoke-ps2exe @parameters

if (Test-Path $exeFile) {
    Write-Host 'Build concluída.' -ForegroundColor Green
    exit 0
}

Write-Error 'O exe não foi gerado.'
exit 1
